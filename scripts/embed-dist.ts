import fs from "fs";
import path from "path";

const distDir = path.resolve(process.cwd(), "frontend", "dist");
const outFilePath = path.resolve(process.cwd(), "server", "embeddedAssets.ts");

if (!fs.existsSync(distDir)) {
  console.error("Error: frontend/dist directory not found. Run frontend build first.");
  process.exit(1);
}

function getMimeType(filePath: string): string {
  const ext = path.extname(filePath).toLowerCase();
  switch (ext) {
    case ".html":
      return "text/html; charset=utf-8";
    case ".js":
      return "application/javascript; charset=utf-8";
    case ".css":
      return "text/css; charset=utf-8";
    case ".json":
      return "application/json; charset=utf-8";
    case ".svg":
      return "image/svg+xml";
    case ".png":
      return "image/png";
    case ".jpg":
    case ".jpeg":
      return "image/jpeg";
    case ".ico":
      return "image/x-icon";
    case ".woff2":
      return "font/woff2";
    default:
      return "application/octet-stream";
  }
}

interface EmbeddedAsset {
  mime: string;
  base64: string;
}

const assets: Record<string, EmbeddedAsset> = {};

function walkDir(currentDir: string) {
  const entries = fs.readdirSync(currentDir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(currentDir, entry.name);
    if (entry.isDirectory()) {
      walkDir(fullPath);
    } else if (entry.isFile()) {
      const relPath = "/" + path.relative(distDir, fullPath).replace(/\\/g, "/");
      const content = fs.readFileSync(fullPath);
      assets[relPath] = {
        mime: getMimeType(fullPath),
        base64: content.toString("base64"),
      };
    }
  }
}

walkDir(distDir);
fs.mkdirSync(path.dirname(outFilePath), { recursive: true });

const outputSource = `// AUTO-GENERATED BY scripts/embed-dist.ts - DO NOT EDIT MANUALLY
export interface EmbeddedAsset {
  mime: string;
  base64: string;
}

export const EMBEDDED_ASSETS: Record<string, EmbeddedAsset> = ${JSON.stringify(assets, null, 2)};
`;

fs.writeFileSync(outFilePath, outputSource, "utf-8");
console.log(
  `[embed-dist] Embedded ${Object.keys(assets).length} frontend dist files into server/embeddedAssets.ts`
);
